/** Map IIgs TEXT_COLORS entry to ARGB8888 used by the VGA text rasterizer. */
uint32_t gs_color_argb(uint8_t index) {
    const RGBA_t c = AppleIIgs::TEXT_COLORS[index & 0x0F];
    return (0xFFu << 24) | (uint32_t(c.r) << 16) | (uint32_t(c.g) << 8) | uint32_t(c.b);
}

/**
 * Program DAC 0–3 from TBCOLOR like ROM `set_textmode_palette`, and blink
 * flash via DAC 2/3 swap (`setup_textmode_palette`). Attr classes stay
 * 0x01 / 0x10 / 0x23 — never stuff GS indices into IBM palette slots.
 */
void apply_a2_text_dac(const display_state_t *ds, bool flash_on) {
    uint8_t fg = (ds->text_color >> 4) & 0x0F;
    uint8_t bg = ds->text_color & 0x0F;
    if (fg == 0 && bg == 0) {
        fg = 0x0F; // white on black fallback
    }
    vga_text_9x16_set_a2_text_dac(gs_color_argb(bg), gs_color_argb(fg), flash_on);
}

/**
 * Apple II cell → VGA glyph + ROM attribute class (0x01 / 0x10 / 0x23).
 * Colors come from DAC slots programmed by apply_a2_text_dac.
 */
void a2_cell_to_vga(uint8_t a2_ch, bool altcharset, uint8_t *out_ch, uint8_t *out_attr) {
    const uint8_t *char_map = altcharset ? kA2CharMouse : kA2CharPrimary;
    const uint8_t *attr_map = altcharset ? kA2AttrMouse : kA2AttrPrimary;
    *out_ch = char_map[a2_ch];
    *out_attr = attr_map[a2_ch];
}

/** Same cadence as VideoScanGenerator: toggle every 15 display frames (~2 Hz). */
bool advance_flash_phase(display_state_t *ds) {
    static uint32_t flash_counter = 0;
    flash_counter++;
    if (flash_counter > 14) {
        ds->flash_state = !ds->flash_state;
        flash_counter = 0;
    }
    return ds->flash_state;
}

void write_row_cells(uint8_t *row, int cols, const uint8_t *src, bool altcharset) {
    for (int x = 0; x < cols; ++x) {
        uint8_t ch;
        uint8_t attr;
        a2_cell_to_vga(src[x], altcharset, &ch, &attr);
        row[x * 2] = ch;
        row[x * 2 + 1] = attr;
    }
}

