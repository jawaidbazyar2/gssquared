void ss_sync_a2_text_to_vga(const uint8_t *a2_ram, uint8_t *vga_base, int pitch,
                            display_state_t *ds) {
    if (!a2_ram || !vga_base || !ds) {
        return;
    }

    // With 80STORE on, PAGE2 selects aux for CPU access (even columns), not
    // display page 2 — video scanner forces page 1. Match that here.
    const bool store80 = ds->video_scanner && ds->video_scanner->is_80store();
    const uint32_t page =
        (!store80 && ds->display_page_num == DISPLAY_PAGE_2) ? 2u : 1u;
    // SS frame processor runs before / instead of VSG, so advance flash here.
    const bool flash_on = advance_flash_phase(ds);
    apply_a2_text_dac(ds, flash_on);
    const bool col80 = ds->f_80col;
    const bool altcharset = ds->f_altcharset;
    const int cols = col80 ? VGA_TEXT_COLS : VGA_TEXT_COLS_40;
    const int min_pitch = cols * VGA_TEXT_CELL_BYTES;
    if (pitch < min_pitch) {
        return;
    }

    uint8_t linear[text_page::kRows * text_page::kCols80];
    if (col80) {
        text_page::linearize_text80(a2_ram, page, linear);
    } else {
        text_page::linearize_text40(a2_ram, page, linear);
    }

    for (uint32_t row = 0; row < text_page::kRows; ++row) {
        uint8_t *dst = vga_base + row * pitch;
        const uint8_t *src = linear + row * cols;
        write_row_cells(dst, cols, src, altcharset);
    }

    // Mode 01h/03h are 25 rows; clear the unused 25th row (normal attr 0x01).
    uint8_t *last = vga_base + text_page::kRows * pitch;
    for (int x = 0; x < cols; ++x) {
        last[x * 2] = ' ';
        last[x * 2 + 1] = 0x01;
    }
}
