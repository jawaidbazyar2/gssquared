bool ss_apple2_fullscreen_text(const display_state_t *ds) {
    if (!ds) {
        return false;
    }
    if (ds->display_mode != TEXT_MODE) {
        return false;
    }
    if (ds->new_video & 0x80) {
        return false; // SHR — not classic A2 text
    }
    return true;
}

