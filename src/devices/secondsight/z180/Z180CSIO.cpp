/*
 *   Clocked serial input/output inside Second Sight's Zilog Z8S180.
 *   CSI/O sends or receives one byte using a separate CKS clock wire. It is
 *   half duplex: software chooses transmit or receive, not both at once.
 *   TXS is transmitted data and RXS received data. CNTR is the control/status
 *   register; TRDR is the unbuffered transmit/receive data register.
 *
 *   The CPU internal-port decoder calls these register methods. The CPU
 *   scheduler calls dispatch for internal-clock edges; this board model drives
 *   no external clock or data input. Output callbacks report changed voltage
 *   levels. Second Sight leaves these serial outputs unconnected, but its CPU
 *   still has the registers.
 *   The Z180 owns this device and all methods run on its execution thread.
 *
 *   PHI is the processor clock. A deadline is an emulated instant, not host
 *   wall time. Source: Zilog UM005004-0918 pp. 147-156, especially Table 22
 *   and Figs. 59-62 for the clock divider and data edges.
 */

#include "Z180CSIO.hpp"
// Zilog UM0050 pp. 149-153: CNTR enable/status and clock source fields.
// 0x0a CSI/O control/status register (EF is read-only)
// EF: eight bits completed; EIE: completion interrupt enable; RE/TE:
// receive/transmit enable; SS: divider select 0-6 or external clock at 7.
// Bit 3 is reserved and reads zero (UM0050 pp. 149-150).
static constexpr uint8_t Z180_CNTR_EF = 0x80;
static constexpr uint8_t Z180_CNTR_EIE = 0x40;
static constexpr uint8_t Z180_CNTR_RE = 0x20;
static constexpr uint8_t Z180_CNTR_TE = 0x10;
static constexpr uint8_t Z180_CNTR_SS = 0x07;

static constexpr uint8_t Z180_CNTR_MASK = 0xf7;

// Return control/status with reserved bit 3 zero; reading does not acknowledge completion (p. 149).
uint8_t Z180CSIO::cntr_r() {

    return cntr & Z180_CNTR_MASK;
}

// Return the unbuffered data byte and clear completion unless peeking (UM0050 p. 151).
uint8_t Z180CSIO::trdr_r() {
    // UM0050 pp. 149, 151: TRDR is unbuffered; the first transmit write
    // precedes EF. Access clears EF rather than being gated by it.

    if (!side_effects_disabled)
        cntr &= ~Z180_CNTR_EF;

    return trdr;
}

// Write byte data as enables and clock selection while preserving the read-only end flag (pp. 149-152).
void Z180CSIO::cntr_w(uint8_t data) {
    if (io_stopped)
        data &= ~(Z180_CNTR_RE | Z180_CNTR_TE);
    // UM0050 pp. 149, 152 requires half-duplex operation. Both bits are
    // retained on an invalid simultaneous enable; no precedence is specified.

    if (data & (Z180_CNTR_RE | Z180_CNTR_TE)) {
        // if receive or transmit will be enabled, start clock if necessary
        if (!(cntr & (Z180_CNTR_RE | Z180_CNTR_TE))) {
            if ((data & Z180_CNTR_SS) != 7)
                timer.adjust(Z180Time::from_hz(clock_rate));
            else
                timer.adjust(Z180Time::never);
        }
    } else {
        shift_cnt = 0;
        if (!cks_out) {
            cks_out = 1;
            if ((data & Z180_CNTR_SS) != 7)
                if (cks_cb)
                    cks_cb(1);
        }
        timer.adjust(Z180Time::never);
    }

    // UM0050 p. 152 requires TE/RE clear when changing the clock source.
    // No synthetic CKS edge is generated by a source change.

    cntr = (cntr & Z180_CNTR_EF) | (data & ~Z180_CNTR_EF & Z180_CNTR_MASK); // EF is read-only
}

// Load unbuffered byte data and clear completion before the next transfer (UM0050 p. 151).
void Z180CSIO::trdr_w(uint8_t data) {
    // UM0050 pp. 149, 151: TRDR is unbuffered; the first transmit write
    // precedes EF. Access clears EF rather than being gated by it.

    cntr &= ~Z180_CNTR_EF;
    trdr = data;
}

// Handle CKS voltage cks: falling sends a bit, rising receives/counts it.
// After eight bits set completion and clear both enables (UM0050 pp. 153-156).
void Z180CSIO::clock_edge(uint8_t cks) {
    if (io_stopped)
        return;
    if (!cks) {
        // TXS updated on falling edge
        if (cntr & Z180_CNTR_TE) {
            uint8_t const txs = z180_bit(trdr, shift_cnt);
            if (txs_out != txs) {
                txs_out = txs;
                if (txs_cb)
                    txs_cb(txs);
            }
        }
    } else {
        // Sample RXS on rising edge (ignore minimum setup/sampling time)
        if (cntr & Z180_CNTR_RE)
            trdr = (trdr & ~(uint8_t(1) << shift_cnt)) | (rxs_in << shift_cnt);

        // EF/RE/TE updated on rising edge
        if (cntr & (Z180_CNTR_RE | Z180_CNTR_TE)) {
            shift_cnt = (shift_cnt + 1) & 7;
            if (!shift_cnt)
                cntr = Z180_CNTR_EF | (cntr & ~(Z180_CNTR_RE | Z180_CNTR_TE));
        }
    }
}

// Reset control and shift position, cancel timing, and publish idle-high outputs (UM0050 pp. 148-150).
void Z180CSIO::reset() {
    io_stopped = false;
    cntr = 0x07;
    shift_cnt = 0;
    irq = 0;
    cks_out = 1;
    txs_out = 1; // Model idle level; Second Sight does not connect TXS.

    timer.adjust(Z180Time::never);

    if (cks_cb)
        cks_cb(cks_out);
    if (txs_cb)
        txs_cb(txs_out);
}

// Toggle CKS and schedule the next half-period using CNTR.SS (UM0050 p. 150, Table 22).
void Z180CSIO::internal_clock() {
    if ((cntr & Z180_CNTR_SS) != 7) {
        cks_out ^= 1;
        if (cks_cb)
            cks_cb(cks_out);
        clock_edge(cks_out);

        if (cntr & (Z180_CNTR_RE | Z180_CNTR_TE)) {
            int div;
            switch (cntr & Z180_CNTR_SS) {
            default:
            case 0:
                div = 20;
                break;
            case 1:
                div = 40;
                break;
            case 2:
                div = 80;
                break;
            case 3:
                div = 160;
                break;
            case 4:
                div = 320;
                break;
            case 5:
                div = 640;
                break;
            case 6:
                div = 1280;
                break;
            }
            timer.adjust(Z180Time::from_hz(clock_rate / div));
        }
    }
}

// Apply the documented I/O-stop register effects; a transfer must be enabled
// again by software after this stop.
// Stop internal I/O when stopped is true; clear enables/completion and retain data (UM0050 pp. 148-149).
void Z180CSIO::set_iostop(bool stopped) {
    io_stopped = stopped;
    if (stopped) {
        // UM0050 pp148-149: EF/RE/TE clear; EIE, SS and TRDR are retained.
        cntr &= ~(Z180_CNTR_EF | Z180_CNTR_RE | Z180_CNTR_TE);
        cntr_w(cntr);
    }
}
